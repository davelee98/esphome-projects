"""Copy native Terminus BDF pixels into the display's 14/24/32 px assets.

Pillow is only used to write PNGs, not to rasterize or scale fonts.
Source: Terminus Font 4.49.1, https://terminus-font.sourceforge.net/
Run: python tools/build_display_fonts.py
     python tools/build_display_fonts.py --dashboard components/aqi_dashboard
       (also writes the firmware's dashboard_assets.h / .cpp: text 14 px,
       bold text 24 px, bold 32 px and the PM-unit sprite only)
"""

import argparse
import json
from pathlib import Path

from PIL import Image, ImageDraw


NUMERIC = "0123456789.- °FC%"
TEXT = "".join(chr(code) for code in range(32, 127)) + "°µ³"


def read_bdf(source):
    lines = iter(source.read_text(encoding="ascii").splitlines())
    size = ascent = None
    glyphs = {}
    for line in lines:
        key, _, value = line.partition(" ")
        if key == "PIXEL_SIZE":
            size = int(value)
        elif key == "FONT_ASCENT":
            ascent = int(value)
        elif key == "STARTCHAR":
            glyph = {}
            for entry in lines:
                field, _, values = entry.partition(" ")
                if field == "ENCODING":
                    glyph["codepoint"] = int(values)
                elif field == "DWIDTH":
                    glyph["advance"] = int(values.split()[0])
                elif field == "BBX":
                    width, height, left, bottom = map(int, values.split())
                    glyph.update(width=width, height=height, left=left,
                                 top=-height-bottom)
                elif field == "BITMAP":
                    glyph["bitmap"] = bytes.fromhex("".join(
                        next(lines).strip() for _ in range(glyph["height"])))
                elif field == "ENDCHAR":
                    if glyph["codepoint"] >= 0:
                        stride = (glyph["width"] + 7) // 8
                        assert len(glyph["bitmap"]) == stride * glyph["height"]
                        glyphs[glyph["codepoint"]] = glyph
                    break
    if size is None or ascent is None:
        raise ValueError(f"Missing native BDF metrics: {source}")
    return size, ascent, glyphs


def bitmap_font(source, size, characters):
    native_size, ascent, original = read_bdf(source)
    if size != native_size:
        raise ValueError(f"{source.name} is native {native_size}px, not {size}px")
    data = bytearray()
    glyphs = []
    for codepoint in sorted(set(map(ord, characters))):
        if codepoint not in original:
            raise ValueError(f"Missing U+{codepoint:04X} in {source.name}")
        glyph = original[codepoint].copy()
        pixels = glyph.pop("bitmap")
        glyph["offset"] = len(data)
        data.extend(pixels)
        glyphs.append(glyph)
    return {"size": size, "baseline": ascent, "source": source.name,
            "family": "Terminus",
            "weight": "bold" if source.stem.endswith("b") else "normal",
            "glyphs": glyphs, "data": list(data)}


def c_header(fonts):
    lines = ["/* Generated by tools/build_display_fonts.py; do not edit. */",
             "/* Native Terminus pixels, SIL OFL 1.1: see terminus/OFL.TXT. */",
             "#ifndef SEN65_NUMERIC_GLYPHS_H", "#define SEN65_NUMERIC_GLYPHS_H",
             "#include <stdint.h>", "",
             "/* Rows are byte padded, MSB first. top is relative to baseline. */",
             "typedef struct {",
             "  uint32_t codepoint;",
             "  uint16_t offset, width, height, advance;",
             "  int16_t left, top;",
             "} sen65_numeric_glyph_t;", "",
             "typedef struct {",
             "  uint16_t size, baseline, glyph_count;",
             "  const sen65_numeric_glyph_t *glyphs;",
             "  const uint8_t *bitmap;",
             "} sen65_numeric_font_t;", ""]
    for font in fonts:
        size = font["size"]
        lines.append(f"static const uint8_t sen65_numeric_{size}_bitmap[] = {{")
        data = font["data"]
        for start in range(0, len(data), 16):
            lines.append("  " + ", ".join(f"0x{byte:02x}" for byte in data[start:start+16]) + ",")
        lines.extend(["};", f"static const sen65_numeric_glyph_t sen65_numeric_{size}_glyphs[] = {{"])
        for glyph in font["glyphs"]:
            values = ", ".join(str(glyph[key]) for key in
                               ("codepoint", "offset", "width", "height", "advance", "left", "top"))
            lines.append("  {" + values + "},")
        lines.extend(["};", f"static const sen65_numeric_font_t sen65_numeric_{size} = {{",
                      f"  {size}, {font['baseline']}, {len(font['glyphs'])},",
                      f"  sen65_numeric_{size}_glyphs, sen65_numeric_{size}_bitmap", "};", ""])
    lines.extend(["#endif", ""])
    return "\n".join(lines)


def pm_units_bitmap(source):
    """One compact line, drawn from native 12 px monospaced glyphs."""
    label = "µg/m³"
    font = bitmap_font(source, 12, label)
    glyph_map = {glyph["codepoint"]: glyph for glyph in font["glyphs"]}
    glyphs = [glyph_map[ord(character)] for character in label]
    top = min(glyph["top"] for glyph in glyphs)
    bottom = max(glyph["top"] + glyph["height"] for glyph in glyphs)
    pen = 0
    width = 0
    for glyph in glyphs:
        width = max(width, pen + glyph["left"] + glyph["width"])
        pen += glyph["advance"]
    height = bottom - top
    height += height % 2  # Keep vertical centering on an integer pixel.
    image = Image.new("1", (width, height), 0)
    pen = 0
    for glyph in glyphs:
        stride = (glyph["width"] + 7) // 8
        for row in range(glyph["height"]):
            for col in range(glyph["width"]):
                if font["data"][glyph["offset"] + row * stride + col // 8] & (0x80 >> (col % 8)):
                    image.putpixel((pen + glyph["left"] + col,
                                    glyph["top"] - top + row), 1)
        pen += glyph["advance"]
    return pack_bitmap(image, label)


def pack_bitmap(image, label):
    stride = (image.width + 7) // 8
    data = bytearray(stride * image.height)
    transparent = Image.new("RGBA", image.size, (0, 0, 0, 0))
    for y in range(image.height):
        for x in range(image.width):
            if image.getpixel((x, y)):
                data[y * stride + x // 8] |= 0x80 >> (x % 8)
                transparent.putpixel((x, y), (0, 0, 0, 255))
    return {"label": label, "width": image.width, "height": image.height,
            "data": list(data)}, transparent


def climate_icons():
    thermometer = Image.new("1", (24, 24), 0)
    draw = ImageDraw.Draw(thermometer)
    draw.rounded_rectangle((9, 1, 15, 18), radius=3, fill=1)
    draw.ellipse((6, 11, 18, 23), fill=1)
    draw.rounded_rectangle((11, 3, 13, 17), radius=1, fill=0)
    draw.ellipse((8, 13, 16, 21), fill=0)
    draw.line((12, 8, 12, 17), fill=1, width=1)
    draw.ellipse((10, 15, 14, 19), fill=1)
    draw.line((17, 5, 20, 5), fill=1, width=2)
    draw.line((17, 9, 19, 9), fill=1, width=2)

    droplet = Image.new("1", (24, 24), 0)
    draw = ImageDraw.Draw(droplet)
    curves = [((12, 1), (14, 5), (21, 10), (21, 14)),
              ((21, 14), (21, 19), (17, 23), (12, 23)),
              ((12, 23), (7, 23), (3, 19), (3, 14)),
              ((3, 14), (3, 10), (10, 5), (12, 1))]
    points = []
    for start, first, second, end in curves:
        for step in range(17):
            t = step / 16
            points.append(tuple(round((1-t)**3*start[i] + 3*(1-t)**2*t*first[i]
                                      + 3*(1-t)*t*t*second[i] + t**3*end[i])
                                for i in range(2)))
    draw.line(points, fill=1, width=2, joint="curve")
    draw.arc((7, 10, 17, 20), 100, 175, fill=1, width=2)
    return {"temperature": pack_bitmap(thermometer, "Temperature"),
            "humidity": pack_bitmap(droplet, "Relative humidity")}


def climate_icons_header(icons):
    lines = ["/* Generated by tools/build_display_fonts.py; do not edit. */",
             "#ifndef SEN65_CLIMATE_ICONS_H", "#define SEN65_CLIMATE_ICONS_H",
             "#include <stdint.h>", "",
             "#define SEN65_CLIMATE_ICON_WIDTH 24",
             "#define SEN65_CLIMATE_ICON_HEIGHT 24",
             "/* MSB-first rows. 1 = foreground; 0 = transparent. */"]
    for name, (bitmap, _) in icons.items():
        lines.append(f"static const uint8_t sen65_{name}_icon[] = {{")
        for start in range(0, len(bitmap["data"]), 16):
            lines.append("  " + ", ".join(f"0x{byte:02x}" for byte in bitmap["data"][start:start+16]) + ",")
        lines.extend(["};", ""])
    lines.extend(["#endif", ""])
    return "\n".join(lines)


def pm_units_header(bitmap):
    lines = ["/* Generated by tools/build_display_fonts.py; do not edit. */",
             "/* Native Terminus pixels, SIL OFL 1.1: see terminus/OFL.TXT. */",
             "#ifndef SEN65_PM_UNITS_H", "#define SEN65_PM_UNITS_H",
             "#include <stdint.h>", "",
             f"#define SEN65_PM_UNITS_WIDTH {bitmap['width']}",
             f"#define SEN65_PM_UNITS_HEIGHT {bitmap['height']}",
             "/* Rows are byte padded, MSB first. 1 = foreground; 0 = transparent. */",
             "static const uint8_t sen65_pm_units_bitmap[] = {"]
    for start in range(0, len(bitmap["data"]), 16):
        lines.append("  " + ", ".join(f"0x{byte:02x}" for byte in bitmap["data"][start:start+16]) + ",")
    lines.extend(["};", "", "#endif", ""])
    return "\n".join(lines)


DASHBOARD_HEADER = """/* Generated by tools/build_display_fonts.py --dashboard; do not edit. */
/* Native Terminus pixels, SIL OFL 1.1: see fonts/terminus/OFL.TXT. */
#pragma once

#include <cstdint>

namespace esphome::aqi_dashboard {

/* Rows are byte padded, MSB first; stride = (width + 7) / 8. top is relative
   to the baseline (negative = above it). Glyphs are sorted by codepoint. */
struct Glyph {
  uint32_t codepoint;
  uint16_t offset, width, height, advance;
  int16_t left, top;
};

struct Font {
  uint16_t size, baseline, glyph_count;
  const Glyph *glyphs;
  const uint8_t *bitmap;
};

/* 1 = foreground, 0 = transparent. */
struct Sprite {
  uint16_t width, height, stride;
  const uint8_t *data;
};

extern const Font FONT_TEXT14;   /* ter-u14n: ASCII 0x20-0x7E plus degree, micro, superscript 3 */
extern const Font FONT_TEXT24;   /* ter-u24b: the same set, bold; header, labels, degree and % units */
extern const Font FONT_BOLD32;   /* ter-u32b: 0123456789.- degree F C % */
extern const Sprite SPRITE_PM_UNITS; /* "ug/m3" in Terminus 6x12, one line */

}  // namespace esphome::aqi_dashboard
"""


def _c_bytes(name, data):
    lines = [f"static const uint8_t {name}[] = {{"]
    for start in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[start:start + 16]) + ",")
    lines.append("};")
    return lines


def dashboard_source(text, text24, bold, units):
    lines = ["/* Generated by tools/build_display_fonts.py --dashboard; do not edit. */",
             "/* Native Terminus pixels, SIL OFL 1.1: see fonts/terminus/OFL.TXT. */",
             '#include "dashboard_assets.h"', "",
             "namespace esphome::aqi_dashboard {", ""]
    for font, name in ((text, "TEXT14"), (text24, "TEXT24"), (bold, "BOLD32")):
        lines += _c_bytes(f"{name}_BITMAP", font["data"])
        lines.append(f"static const Glyph {name}_GLYPHS[] = {{")
        for glyph in font["glyphs"]:
            values = ", ".join(str(glyph[key]) for key in
                               ("codepoint", "offset", "width", "height", "advance", "left", "top"))
            lines.append("    {" + values + "},")
        lines += ["};",
                  f"const Font FONT_{name} = {{{font['size']}, {font['baseline']}, "
                  f"{len(font['glyphs'])}, {name}_GLYPHS, {name}_BITMAP}};", ""]
    stride = (units["width"] + 7) // 8
    lines += _c_bytes("PM_UNITS_BITMAP", units["data"])
    lines += [f"const Sprite SPRITE_PM_UNITS = {{{units['width']}, {units['height']}, {stride}, PM_UNITS_BITMAP}};",
              "", "}  // namespace esphome::aqi_dashboard", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "fonts")
    parser.add_argument("--sheet", type=Path)
    parser.add_argument("--dashboard", type=Path,
                        help="write dashboard_assets.h/.cpp for the firmware into this directory")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    sources = args.output / "terminus"
    fonts = [bitmap_font(sources / "ter-u14n.bdf", 14, TEXT),
             bitmap_font(sources / "ter-u24b.bdf", 24, NUMERIC),
             bitmap_font(sources / "ter-u32b.bdf", 32, NUMERIC)]
    units, units_image = pm_units_bitmap(sources / "ter-u12n.bdf")
    icons = climate_icons()
    payload = {"family": "Terminus", "bpp": 1,
               "numeric_characters": NUMERIC, "fonts": fonts, "pm_units": units,
               "icons": {name: bitmap for name, (bitmap, _) in icons.items()}}
    (args.output / "display-glyphs.json").write_text(
        json.dumps(payload, separators=(",", ":")), encoding="utf-8")
    (args.output / "numeric-glyphs.h").write_text(c_header(fonts[1:]), encoding="utf-8")
    (args.output / "pm-units.h").write_text(pm_units_header(units), encoding="utf-8")
    units_image.save(args.output / "pm-units.png")
    (args.output / "climate-icons.h").write_text(climate_icons_header(icons), encoding="utf-8")
    for name, (_, image) in icons.items():
        image.save(args.output / f"{name}-icon.png")
    if args.dashboard:
        args.dashboard.mkdir(parents=True, exist_ok=True)
        (args.dashboard / "dashboard_assets.h").write_text(DASHBOARD_HEADER, encoding="utf-8", newline="\n")
        (args.dashboard / "dashboard_assets.cpp").write_text(
            dashboard_source(fonts[0], bitmap_font(sources / "ter-u24b.bdf", 24, TEXT), fonts[2], units),
            encoding="utf-8", newline="\n")
    if args.sheet:
        sheet = Image.new("1", (640, 200), 1)
        draw = ImageDraw.Draw(sheet)
        for font, y in [(fonts[1], 26), (fonts[2], 94)]:
            pen = 12
            for character in NUMERIC:
                glyph = next(g for g in font["glyphs"] if g["codepoint"] == ord(character))
                stride = (glyph["width"] + 7) // 8
                for row in range(glyph["height"]):
                    for col in range(glyph["width"]):
                        if font["data"][glyph["offset"] + row*stride + col//8] & (0x80 >> (col % 8)):
                            draw.point((pen + glyph["left"] + col,
                                        y + font["baseline"] + glyph["top"] + row), fill=0)
                pen += glyph["advance"]
        args.sheet.parent.mkdir(parents=True, exist_ok=True)
        sheet.save(args.sheet)
    print(json.dumps({"fonts": [{"size": f["size"], "glyphs": len(f["glyphs"]),
                                 "bitmap_bytes": len(f["data"])} for f in fonts],
                      "pm_units": {"width": units["width"], "height": units["height"],
                                   "bitmap_bytes": len(units["data"])}}))


if __name__ == "__main__":
    main()
